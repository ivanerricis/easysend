import { describe, expect, it } from 'vitest';
import { ERROR_CODES } from '../schemas/errors.js';
import { ENDPOINT_TAGS, SAFE_METHODS, implicitErrors, pathParamNames } from './endpoint.js';
import { endpoints } from './endpoints.js';
import { ERROR_MEANINGS } from './doc-text.js';
import { tusHookErrors } from './tus.js';
import { renderApiDocs } from './render-md.js';

describe('endpoint registry', () => {
  it('has unique ids and unique method+path pairs', () => {
    const ids = endpoints.map((e) => e.id);
    expect(new Set(ids).size).toBe(ids.length);
    const keys = endpoints.map((e) => `${e.method} ${e.path}`);
    expect(new Set(keys).size).toBe(keys.length);
  });

  it('keeps every path under /api and every id prefixed by a known tag area', () => {
    for (const e of endpoints) {
      expect(e.path.startsWith('/api/')).toBe(true);
      expect(ENDPOINT_TAGS).toContain(e.tag);
    }
  });

  it('matches :param placeholders with the keys of the params schema', () => {
    for (const e of endpoints) {
      const fromPath = pathParamNames(e.path).sort();
      const fromSchema = e.params ? Object.keys(e.params.shape).sort() : [];
      expect(fromSchema, `${e.method} ${e.path}`).toEqual(fromPath);
    }
  });

  it('references only known error codes', () => {
    for (const e of endpoints) {
      for (const code of [...e.errors, ...implicitErrors(e)]) {
        expect(ERROR_CODES, `${e.id}: ${code}`).toHaveProperty(code);
      }
    }
    for (const h of tusHookErrors) expect(ERROR_CODES).toHaveProperty(h.code);
    expect(Object.keys(ERROR_MEANINGS).sort()).toEqual(Object.keys(ERROR_CODES).sort());
  });

  it('has no body on GET and HEAD', () => {
    for (const e of endpoints.filter((x) => x.method === 'GET' || x.method === 'HEAD')) {
      expect(e.body, e.id).toBeUndefined();
      expect(e.rawBody, e.id).toBeUndefined();
    }
  });

  it('never declares both a JSON body and a raw body', () => {
    for (const e of endpoints) expect(!(e.body && e.rawBody), e.id).toBe(true);
  });

  it('requires CSRF on unsafe non-public endpoints and never on safe methods', () => {
    for (const e of endpoints) {
      const unsafe = !SAFE_METHODS.includes(e.method);
      if (unsafe && e.auth !== 'public') expect(e.csrf, e.id).toBe(true);
      if (!unsafe) expect(e.csrf, e.id).toBe(false);
    }
  });

  it('only exempts public token-based download endpoints from CSRF on unsafe methods', () => {
    const exempt = endpoints.filter((e) => !SAFE_METHODS.includes(e.method) && !e.csrf);
    for (const e of exempt) {
      expect(e.auth, e.id).toBe('public');
      expect(e.tag, e.id).toBe('downloads');
    }
  });

  it('declares a schema for every JSON response', () => {
    for (const e of endpoints) {
      if (e.response.kind === 'json') expect(e.response.schema, e.id).toBeDefined();
      else expect(e.response.schema, e.id).toBeUndefined();
    }
  });

  it('covers every tag', () => {
    for (const tag of ENDPOINT_TAGS) {
      expect(
        endpoints.some((e) => e.tag === tag),
        tag,
      ).toBe(true);
    }
  });
});

describe('renderApiDocs', () => {
  it('is deterministic', () => {
    expect(renderApiDocs(endpoints)).toBe(renderApiDocs(endpoints));
  });

  it('contains every endpoint and uses LF line endings', () => {
    const md = renderApiDocs(endpoints);
    for (const e of endpoints) expect(md).toContain(`\`${e.method} ${e.path}\``);
    expect(md).not.toContain('\r');
    expect(md.startsWith('<!-- Generated by pnpm api:docs from packages/shared.')).toBe(true);
    expect(md.endsWith('\n')).toBe(true);
    expect(md.endsWith('\n\n')).toBe(false);
  });

  it('documents every error code, the tus section and the decisions', () => {
    const md = renderApiDocs(endpoints);
    for (const code of Object.keys(ERROR_CODES)) expect(md).toContain(`\`${code}\``);
    expect(md).toContain('### tus protocol');
    expect(md).toContain('## Decisions to approve');
  });
});
